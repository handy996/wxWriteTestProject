"""CI uses the delivered Compose topology on an isolated project/volume.

No production deployment. Only this randomly named test project is removed.
"""
import argparse
import json
import os
from pathlib import Path
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
import uuid

sys.stdout.reconfigure(encoding='utf-8', errors='replace')
sys.stderr.reconfigure(encoding='utf-8', errors='replace')
ROOT = Path(__file__).resolve().parents[3]
parser = argparse.ArgumentParser()
parser.add_argument('--entrypoint', action='store_true', help='Exercise dev.py up/down/up on an isolated project')
args = parser.parse_args()
project = 't02-test-' + uuid.uuid4().hex[:12]
env = dict(os.environ, APP_PROFILE='mock', WEB_PORT='18080', COMPOSE_PROJECT_NAME=project)
for role in ('ADMIN', 'MIGRATION', 'RUNTIME'):
    env['DB_' + role + '_PASSWORD'] = secrets.token_hex(24)
base = ['docker', 'compose', '-p', project, '-f', str(ROOT / 'infra/compose.yml')]
env_file = ROOT / 'tests/engineering/T02/.work' / (project + '.env')
env_file.parent.mkdir(parents=True, exist_ok=True)
if args.entrypoint:
    # dev.py generates this file; it must never reuse or overwrite infra/.env.
    assert not env_file.exists()


def command(argv, expected=0):
    result = subprocess.run(argv, cwd=ROOT, env=env, capture_output=True, text=True,
                            encoding='utf-8', errors='replace', timeout=1200)
    # Docker build logs and DB commands contain no credentials; env is never printed.
    output = result.stdout + result.stderr
    credentials = [env.get('DB_' + role + '_PASSWORD') for role in ('ADMIN', 'MIGRATION', 'RUNTIME')]
    if args.entrypoint and env_file.exists():
        credentials.extend(line.split('=', 1)[1] for line in env_file.read_text(encoding='utf-8').splitlines() if '_PASSWORD=' in line)
    for credential in credentials:
        if credential:
            output = output.replace(credential, '[REDACTED]')
    print(json.dumps({'argv': argv, 'exitCode': result.returncode, 'expected': expected}), flush=True)
    print(output, flush=True)
    if expected == 'nonzero':
        assert result.returncode != 0, argv
    else:
        assert result.returncode == expected, argv
    return result.stdout


def run(*parts, expected=0):
    return command(base + list(parts), expected)


def lifecycle(action):
    if args.entrypoint:
        # Use the credentials generated by the actual entrypoint, not the direct
        # Compose test's environment overrides. Keep project and port isolated.
        saved = {key: env.pop(key) for key in ('DB_ADMIN_PASSWORD', 'DB_MIGRATION_PASSWORD', 'DB_RUNTIME_PASSWORD')}
        try:
            return command([sys.executable, str(ROOT / 'backend/scripts/dev.py'), action,
                            '--env-file', str(env_file)])
        finally:
            env.update(saved)
            if env_file.exists():
                generated = dict(line.split('=', 1) for line in env_file.read_text(encoding='utf-8').splitlines() if '=' in line)
                env.update({key: generated[key] for key in saved})
    return run(*(['up', '-d', '--build'] if action == 'up' else ['down']))


def psql(sql, role='editorial_runtime', expected=0):
    return run('exec', '-T', 'db', 'psql', '-v', 'ON_ERROR_STOP=1', '-U', role,
               '-d', 'editorial', '-Atc', sql, expected=expected)


def ready():
    deadline = time.monotonic() + 120
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen('http://127.0.0.1:18080/actuator/health/readiness', timeout=2) as response:
                if response.status == 200:
                    return
        except (OSError, urllib.error.HTTPError):
            pass
        time.sleep(1)
    raise TimeoutError('Compose application readiness')


try:
    run('config', '--quiet')
    lifecycle('up')
    ready()
    assert run('exec', '-T', 'backend', 'id', '-u').strip() == '10001'
    container = run('ps', '-q', 'backend').strip()
    assert command(['docker', 'inspect', '--format', '{{.HostConfig.ReadonlyRootfs}}', container]).strip() == 'true'
    with urllib.request.urlopen('http://127.0.0.1:18080/') as response:
        assert 'id="app"' in response.read().decode()
    with urllib.request.urlopen('http://127.0.0.1:18080/actuator/info') as response:
        info = json.load(response)['skeleton']
        assert info['mode'] == 'mock' and not info['paidCallsEnabled']
        assert len(info['capabilities']) == 4 and all(not item['available'] for item in info['capabilities'])
    try:
        urllib.request.urlopen('http://127.0.0.1:18080/api/v1/articles')
        raise AssertionError('API proxy bypassed backend deny')
    except urllib.error.HTTPError as error:
        assert error.code in (401, 403), error.code
    psql("CREATE TABLE editorial.t02_persistence_probe(id integer PRIMARY KEY); "
         "GRANT SELECT, INSERT ON editorial.t02_persistence_probe TO editorial_runtime; "
         "CREATE FUNCTION editorial.t02_compose_probe() RETURNS integer LANGUAGE sql AS 'SELECT 42'", 'editorial_migrator')
    psql('INSERT INTO editorial.t02_persistence_probe VALUES(42)')
    psql('SELECT editorial.t02_compose_probe()', expected='nonzero')
    psql('GRANT EXECUTE ON FUNCTION editorial.t02_compose_probe() TO editorial_runtime', 'editorial_migrator')
    assert psql('SELECT editorial.t02_compose_probe()').strip() == '42'
    sql = 'SELECT installed_rank,script,checksum,success FROM editorial_migrations.flyway_schema_history ORDER BY installed_rank'
    history = run('exec', '-T', 'db', 'psql', '-U', 'editorial_admin', '-d', 'editorial', '-Atc', sql)
    lifecycle('down')
    lifecycle('up')
    ready()
    assert history == run('exec', '-T', 'db', 'psql', '-U', 'editorial_admin', '-d', 'editorial', '-Atc', sql)
    assert psql('SELECT id FROM editorial.t02_persistence_probe').strip() == '42'
    assert psql('SELECT editorial.t02_compose_probe()').strip() == '42'
    psql("CREATE FUNCTION editorial.t02_compose_after_restart() RETURNS integer LANGUAGE sql AS 'SELECT 42'", 'editorial_migrator')
    psql('SELECT editorial.t02_compose_after_restart()', expected='nonzero')
    for sql in ('CREATE TABLE editorial.t02_forbidden(id int)',
                'CREATE TEMP TABLE t02_forbidden(id int)',
                'SELECT * FROM editorial_migrations.flyway_schema_history', 'SET ROLE editorial_migrator'):
        run('exec', '-T', 'db', 'psql', '-v', 'ON_ERROR_STOP=1', '-U', 'editorial_runtime', '-d', 'editorial', '-c', sql, expected='nonzero')
    rejected = run('run', '--rm', '--no-deps', '-e', 'SPRING_PROFILES_ACTIVE=prod,mock', 'backend', expected='nonzero')
    assert 'T02_PROFILE' in rejected, 'Expected profile guard rejection'
    print('REAL_DOCKER: cold start, down/up, persisted data/history, HTTP/API proxy, function ACLs, permissions and prod/mock guard verified; paid calls=0.')
except Exception:
    run('logs', '--no-color', '--tail', '100')
    raise
finally:
    run('down', '--volumes', '--remove-orphans')
    assert not run('ps', '-aq').strip(), 'Test containers remain'
    remaining = command(['docker', 'volume', 'ls', '-q', '--filter', 'label=com.docker.compose.project=' + project])
    assert not remaining.strip(), 'Test volumes remain'
    if env_file.exists():
        env_file.unlink()
